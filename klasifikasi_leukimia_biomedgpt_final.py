"""## **Langkah 7 — Prompt: bagaimana data pasien "diceritakan" ke LLM**

LLM hanya memahami teks, jadi data numerik pasien diubah menjadi **kalimat prompt**. Strateginya (*zero-shot*, tanpa contoh):

1. Tampilkan **3 gen ekspresi tertinggi (HIGH)** dan **3 gen ekspresi terendah (LOW)** milik pasien tersebut.
2. Beri tahu daftar gen yang sah dan **larang** LLM menyebut gen lain (mencegah halusinasi nama gen).
3. Beri petunjuk klinis singkat: ALL ↔ penanda limfoid, AML ↔ penanda mieloid.
4. Akhiri dengan `Answer: This patient has` supaya LLM **melanjutkan kalimat** dengan diagnosis. Token pertama inilah yang dipakai untuk menghitung probabilitas.

"""

def build_prompt(x_patient, gene_names):
    """Susun prompt zero-shot untuk satu pasien.

    Args:
        x_patient : array (K_GENES,) nilai ekspresi terstandarisasi pasien.
        gene_names: nama gen terpilih, urut sesuai x_patient.
    """
    order     = np.argsort(x_patient)           # urut dari paling rendah ke paling tinggi
    idx_high  = order[-3:][::-1]                # 3 tertinggi
    idx_low   = order[:3]                       # 3 terendah

    genes_high = "\n".join(f"  {gene_names[j]}: {x_patient[j]:.4f} (HIGH)" for j in idx_high)
    genes_low  = "\n".join(f"  {gene_names[j]}: {x_patient[j]:.4f} (LOW)"  for j in idx_low)

    return (
        "You are an expert oncologist specializing in leukemia classification.\n\n"
        f"Available genes for this patient: {', '.join(gene_names)}\n\n"
        f"Highly expressed genes (upregulated):\n{genes_high}\n\n"
        f"Lowly expressed genes (downregulated):\n{genes_low}\n\n"
        "IMPORTANT: ONLY use the gene names listed above in your explanation.\n"
        "Do NOT mention any other gene names.\n\n"
        "ALL shows upregulation of lymphoid markers.\n"
        "AML shows upregulation of myeloid markers.\n\n"
        "Classify as ALL or AML and explain in Portuguese (pt-BR) "
        "citing ONLY the genes listed above with their expression levels.\n\n"
        "Answer: This patient has"
    )


