"""## **Langkah 8 — Klasifikasi satu pasien**

Untuk setiap pasien, LLM melakukan dua hal sekaligus dalam satu pemanggilan `generate`:

**a) Menghasilkan teks penjelasan** (hingga `MAX_NEW_TOKENS` token).

**b) Menghasilkan probabilitas.** Pada posisi token pertama setelah `...This patient has`, model memberi skor (*logit*) ke seluruh kosakata. Skor ini diubah menjadi probabilitas dengan *softmax*, lalu probabilitas token "milik" tiap kelas dijumlahkan:

```
P(ALL) = jumlah probabilitas token  {ALL, Lymph}
P(AML) = jumlah probabilitas token  {AML, Myeloid, Ac}
P(AML) dinormalisasi = P(AML) / (P(ALL) + P(AML))
```

Prediksi = **AML** jika P(AML) > `PROB_THRESHOLD`, selain itu **ALL**. *Confidence* = `max(P(AML), 1 − P(AML))`.

Kita mengambil probabilitas dari logit (bukan dari teks yang dihasilkan) karena angkanya kontinu, sehingga bisa dipakai menghitung **AUC-ROC**.
"""

def get_class_token_ids(tokenizer, class_keywords):
    """Ubah kata kunci tiap kelas menjadi daftar ID token (dihitung sekali saja)."""
    return {
        cls: [tok for kw in keywords for tok in tokenizer.encode(kw, add_special_tokens=False)]
        for cls, keywords in class_keywords.items()
    }


def compute_prob_aml(first_token_logits, token_ids):
    """Hitung P(AML) ternormalisasi dari logit token pertama."""
    probs = torch.softmax(first_token_logits, dim=-1)
    p_all = sum(probs[t].item() for t in token_ids["ALL"])
    p_aml = sum(probs[t].item() for t in token_ids["AML"])
    return p_aml / (p_all + p_aml + 1e-9)


def classify_patient(x_patient, gene_names, tokenizer, model, token_ids):
    """Klasifikasikan satu pasien. Mengembalikan dict prediksi, probabilitas, dan penjelasan."""
    prompt = build_prompt(x_patient, gene_names)
    inputs = tokenizer(
        prompt, return_tensors="pt", truncation=True, max_length=MAX_PROMPT_TOKENS
    ).to(DEVICE)

    gen_config = GenerationConfig(
        eos_token_id=tokenizer.eos_token_id,
        pad_token_id=tokenizer.eos_token_id,
        **GENERATION_CONFIG,
    )

    with torch.no_grad():
        output = model.generate(
            **inputs,
            generation_config=gen_config,
            output_scores=True,
            return_dict_in_generate=True,
        )

    # (a) teks penjelasan = hasil generate dikurangi prompt
    full_text   = tokenizer.decode(output.sequences[0], skip_special_tokens=True)
    explanation = full_text[len(prompt):].strip()

    # (b) probabilitas dari logit token pertama
    prob_aml   = compute_prob_aml(output.scores[0][0], token_ids)
    prediction = "AML" if prob_aml > PROB_THRESHOLD else "ALL"

    return {
        "prediction" : prediction,
        "prob_aml"   : round(prob_aml, 4),
        "confidence" : round(max(prob_aml, 1 - prob_aml), 4),
        "explanation": explanation if explanation else "(model tidak menghasilkan penjelasan)",
    }


