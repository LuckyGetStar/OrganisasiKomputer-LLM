"""## **Langkah 10 — Evaluasi**

Metrik yang dipakai:

| Metrik | Arti |
|---|---|
| **Accuracy** | Persentase pasien yang diklasifikasikan benar. |
| **F1 (macro)** | Rata-rata F1 ALL dan AML; adil untuk data yang tidak seimbang (47 ALL vs 25 AML). |
| **AUC-ROC** | Kemampuan P(AML) memisahkan dua kelas, terlepas dari ambang 0,5. 0,5 = tebakan acak, 1,0 = sempurna. |
| **Confusion matrix** | Rincian: berapa ALL salah dibaca AML dan sebaliknya. |

Pasien berstatus `ERROR` tidak ikut dihitung.
"""

def evaluate(df, split_name):
    """Hitung dan cetak metrik evaluasi untuk satu split. Mengembalikan dict metrik."""
    d = df[df["prediction"] != "ERROR"]
    y_true = (d["real_label"] == "AML").astype(int).values
    y_pred = (d["prediction"] == "AML").astype(int).values

    metrics = {
        "split"   : split_name,
        "n"       : len(d),
        "accuracy": accuracy_score(y_true, y_pred),
        "f1_macro": f1_score(y_true, y_pred, average="macro"),
        # AUC hanya terdefinisi jika kedua kelas ada
        "auc_roc" : roc_auc_score(y_true, d["prob_aml"].astype(float))
                    if len(np.unique(y_true)) == 2 else float("nan"),
    }

    print(f"\n===== {split_name.upper()} (n={metrics['n']}, error={len(df) - len(d)}) =====")
    print(f"Accuracy : {metrics['accuracy']:.4f}")
    print(f"F1 macro : {metrics['f1_macro']:.4f}")
    print(f"AUC-ROC  : {metrics['auc_roc']:.4f}")
    print("\nConfusion matrix (baris = asli, kolom = prediksi):")
    print(pd.crosstab(d["real_label"], d["prediction"]))
    print("\n" + classification_report(y_true, y_pred, target_names=CLASS_NAMES, zero_division=0))
    return metrics


