"""## **Langkah 5 — Preprocessing: standarisasi dan pemilihan gen**

Dataset ini punya **7.129 fitur tetapi hanya 72 pasien** (masalah *curse of dimensionality*), dan LLM tidak mungkin membaca ribuan angka dalam satu prompt. Maka ada dua tahap:

1. **`StandardScaler`**: ubah tiap gen ke skala yang sama (rata-rata 0, simpangan baku 1). Nilai positif berarti ekspresi di atas rata-rata (**HIGH**), negatif di bawah rata-rata (**LOW**).
2. **`SelectKBest` + ANOVA F-test**: pilih `K_GENES` gen yang paling membedakan ALL dari AML.

> **Penting (mencegah *data leakage*):** scaler dan selector hanya di-*fit* pada **data latih**, lalu diterapkan ke data uji. Data uji tidak boleh ikut menentukan gen terpilih.
"""

def preprocess(X_train, y_train, X_test, gene_names, k):
    """Standarisasi lalu pilih k gen paling diskriminatif (fit hanya pada data latih)."""
    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_test_scaled  = scaler.transform(X_test)

    selector = SelectKBest(score_func=f_classif, k=k)
    X_train_sel = selector.fit_transform(X_train_scaled, y_train)
    X_test_sel  = selector.transform(X_test_scaled)

    selected_genes = [gene_names[i] for i in selector.get_support(indices=True)]
    return X_train_sel, X_test_sel, selected_genes


