"""## **Langkah 9 — Menjalankan inferensi pada seluruh pasien**

`run_inference` mengulang `classify_patient` untuk setiap pasien dan menyusun hasilnya menjadi satu tabel (*DataFrame*). Dua hal untuk keamanan di Colab:

- **Penyimpanan bertahap**: CSV ditulis ulang setiap selesai satu pasien, sehingga hasil tidak hilang jika sesi terputus.
- **`try/except`**: jika satu pasien error, ia dicatat sebagai `ERROR` dan perulangan tetap berlanjut.

"""

def run_inference(split_name, X_sel, y, patient_ids):
    """Klasifikasikan semua pasien pada satu split dan kembalikan DataFrame hasil."""
    # Untuk uji cepat: ambil pasien yang tersebar merata agar kedua kelas ikut terambil
    n_total = len(X_sel)
    if MAX_PATIENTS is None or MAX_PATIENTS >= n_total:
        indices = list(range(n_total))
    else:
        indices = np.linspace(0, n_total - 1, MAX_PATIENTS).astype(int).tolist()

    save_path = f"{OUTPUT_DIR}/hasil_{split_name}.csv"
    records = []
    print(f"=== {split_name.upper()}: {len(indices)} pasien ===")

    for step, i in enumerate(indices, start=1):
        real_label = CLASS_NAMES[y[i]]
        try:
            res = classify_patient(X_sel[i], selected_genes, tokenizer, model, token_ids)
            correct = res["prediction"] == real_label
            record = {
                "patient_id": patient_ids[i], "split": split_name, "real_label": real_label,
                **res, "correct": correct, "n_words": len(res["explanation"].split()),
            }
            print(f"  [{'OK  ' if correct else 'FAIL'}] pasien {patient_ids[i]:>2} | "
                  f"asli={real_label} | prediksi={res['prediction']} | conf={res['confidence']:.3f}")
        except Exception as e:                       # satu pasien gagal -> lanjut ke berikutnya
            record = {
                "patient_id": patient_ids[i], "split": split_name, "real_label": real_label,
                "prediction": "ERROR", "prob_aml": None, "confidence": None,
                "explanation": str(e), "correct": False, "n_words": 0,
            }
            print(f"  [ERR ] pasien {patient_ids[i]:>2} | {e}")

        records.append(record)
        pd.DataFrame(records).to_csv(save_path, index=False)    # simpan bertahap

        if step % 10 == 0:
            torch.cuda.empty_cache()                            # jaga memori GPU

    return pd.DataFrame(records)


