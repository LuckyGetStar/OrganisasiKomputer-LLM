"""## **Langkah 4 — Memuat dan merapikan data**
Pada file CSV, **baris = gen** dan **kolom = pasien**. Untuk klasifikasi kita butuh kebalikannya: **baris = pasien** dan **kolom = gen**. Selain itu setiap pasien punya kolom pendamping `call`, `call.1`, `call.2`, ... (penilaian kualitatif A/P/M) yang bukan nilai ekspresi dan harus dibuang.

Fungsi `load_split` melakukan 4 hal secara berurutan:
1. Baca CSV.
2. Ambil hanya kolom yang namanya **angka** (= ID pasien); kolom `call*` otomatis terbuang.
3. Transpose menjadi matriks `pasien × gen`.
4. Cocokkan label dari `actual.csv` berdasarkan ID pasien.
"""

def load_split(csv_path, label_map):
    """Muat satu file CSV ekspresi gen dan ubah menjadi matriks pasien x gen.

    Args:
        csv_path : lokasi file CSV (train atau independent/test).
        label_map: dict {id_pasien: "ALL"/"AML"} dari actual.csv.

    Returns:
        X           : array (n_pasien, n_gen) berisi nilai ekspresi.
        y           : array (n_pasien,) label 0 (ALL) atau 1 (AML).
        patient_ids : list ID pasien sesuai urutan baris X.
        gene_names  : list nomor akses gen sesuai urutan kolom X.
    """
    df = pd.read_csv(csv_path)
    gene_names = df["Gene Accession Number"].tolist()

    patient_cols = [c for c in df.columns if c.isdigit()]   # buang 'call', 'call.1', ...
    patient_ids  = [int(c) for c in patient_cols]

    X = df[patient_cols].T.values.astype(float)             # transpose -> pasien x gen
    y = np.array([LABEL_TO_INT[label_map[p]] for p in patient_ids])
    return X, y, patient_ids, gene_names


