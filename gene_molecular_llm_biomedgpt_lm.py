from wordcloud import WordCloud, STOPWORDS

# Extend default stopwords with generic prompt and domain terms

extra_stopwords = {
    "patient", "gene", "expression", "This", "has", "the", "is",
    "a", "of", "and", "in", "that", "to", "with", "for", "are",
    "be", "as", "at", "an", "its", "it", "by", "from", "or",
    "on", "which", "not", "this", "have", "been", "was", "were",
    "high", "low", "highly", "lowly", "expressed", "expression",
    "values", "value", "level", "levels", "Classificacao", "AML",
    "ALL", "diagnosis", "following", "sample", "marker", "markers",
}

stopwords = STOPWORDS.union(extra_stopwords)


def build_text(df, label):
    """
    Concatenate all LLM explanations for a given class into a single string.

    Args:
        df    (pd.DataFrame): DataFrame containing LLM_Explicacao and real_label columns.
        label (str)         : Class label to filter, either 'ALL' or 'AML'.

    Returns:
        str: Single concatenated string of all explanations for the given class.
    """

    # Filter rows by class label and drop missing explanation entries

    subset = df[df["real_label"] == label]["LLM_Explicacao"].dropna()
    return " ".join(subset.tolist())


# Build concatenated explanation strings for each class

text_all = build_text(df_treino, "ALL")
text_aml = build_text(df_treino, "AML")

