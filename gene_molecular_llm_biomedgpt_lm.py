def extract_classification_from_logits(scores, tokenizer):
    """
    Extract classification directly from the logits of the first generated token.

    More reliable than text parsing because it uses the raw model probability
    before any decoding step or text hallucination can occur.

    Args:
        scores    (tuple): Score tensors returned by model.generate().
        tokenizer        : Tokenizer associated with the loaded model.

    Returns:
        tuple: (classification, prob_aml)
            - classification (str)  : Predicted class, either 'ALL' or 'AML'.
            - prob_aml       (float): Normalised probability of AML.
    """

    # Extract logits from the first generated token position

    logits     = scores[0][0]
    proba_soft = torch.softmax(logits, dim=-1)

    # Retrieve token IDs for ALL and AML surface forms and their synonyms

    all_tokens = tokenizer.encode("ALL",     add_special_tokens=False)
    aml_tokens = tokenizer.encode("AML",     add_special_tokens=False)
    lym_tokens = tokenizer.encode("Lymph",   add_special_tokens=False)
    mye_tokens = tokenizer.encode("Myeloid", add_special_tokens=False)
    ac_tokens  = tokenizer.encode("Ac",      add_special_tokens=False)
    a_tokens   = tokenizer.encode("a",       add_special_tokens=False)

    # Aggregate probabilities across all synonym tokens for each class

    p_all = sum(proba_soft[t].item() for t in all_tokens + lym_tokens)
    p_aml = sum(proba_soft[t].item() for t in aml_tokens + mye_tokens + ac_tokens)

    # Normalise and apply threshold to produce the hard prediction

    prob_aml       = p_aml / (p_all + p_aml + 1e-9)
    classification = "AML" if prob_aml > 0.5 else "ALL"

    return classification, prob_aml


