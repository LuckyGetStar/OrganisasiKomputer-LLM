def is_numeric_col(col):
    """
    Check whether a column name can be cast to an integer.

    Used to filter out qualitative annotation columns such as
    'call', 'call.1', and 'call.2' that do not represent
    gene expression values.

    Args:
        col (str): Column name to evaluate.

    Returns:
        bool: True if the column name represents a numeric patient ID.
    """
    try:
        int(col)
        return True
    except (ValueError, TypeError):
        return False


# Retain only numeric patient ID columns
