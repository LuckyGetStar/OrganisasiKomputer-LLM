"""# Part 9 - Prompt Engineering 1"""

"""
Few-shot prompt builder for BioMedGPT-LM-7B.

Uses the Llama2-Chat template with [INST] <<SYS>> tags because the model
was fine-tuned from Llama2-7B-Chat. N_SHOTS examples are split equally
between ALL and AML classes.
"""


def build_prompt(x_examples, y_examples, x_new, gene_names, n_shots):
    """
    Build a few-shot prompt in Llama2-Chat format for BioMedGPT.

    Args:
        x_examples (np.ndarray): Feature matrix of training examples.
        y_examples (np.ndarray): Encoded labels of training examples.
        x_new      (np.ndarray): Feature vector of the patient to classify.
        gene_names (list)      : Names of the selected genes.
        n_shots    (int)       : Total number of few-shot examples.

    Returns:
        str: Formatted prompt ready for the tokenizer.
    """

    # System instruction passed to the model via the SYS block

    system_msg = (
        "You are an expert oncologist specializing in leukemia diagnosis. "
        "Classify the patient as ALL (Acute Lymphoblastic Leukemia) or "
        "AML (Acute Myeloid Leukemia) based on gene expression values. "
        "Answer with only ALL or AML."
    )

    # Select an equal number of ALL and AML examples for balanced few-shot context

    all_idx  = [i for i, y in enumerate(y_examples) if y == 0][: n_shots // 2]
    aml_idx  = [i for i, y in enumerate(y_examples) if y == 1][: n_shots // 2]
    shot_idx = all_idx + aml_idx

    # Build the few-shot example block

    shots = ""
    for idx in shot_idx:
        gene_str = ", ".join(
            [f"{g}: {x_examples[idx][j]:.3f}" for j, g in enumerate(gene_names)]
        )
        label  = "ALL" if y_examples[idx] == 0 else "AML"
        shots += f"Patient gene expression: {gene_str}\nDiagnosis: {label}\n\n"

    # Format the new patient gene expression string

    new_gene_str = ", ".join(
        [f"{g}: {x_new[j]:.3f}" for j, g in enumerate(gene_names)]
    )

    # Assemble the full Llama2-Chat formatted prompt

    return (
        f"[INST] <<SYS>>\n{system_msg}\n<</SYS>>\n\n"
        f"{shots}"
        f"Patient gene expression: {new_gene_str}\n"
        f"Diagnosis: [/INST]"
    )


print("build_prompt defined. Ready to run inference.")

"""
BioMedGPT-LM-7B inference on test patients.

Generates ALL/AML predictions and P(AML) probabilities derived from
the logits of the first generated token, enabling AUC-ROC computation.
"""

# Inference-specific imports

from transformers import GenerationConfig
from sklearn.metrics import (
    accuracy_score,
    f1_score,
    roc_auc_score,
    classification_report,
)

# Generation configuration for deterministic single-token classification

gen_config_clf = GenerationConfig(
    max_new_tokens=10,
    do_sample=False,
    repetition_penalty=1.15,
    no_repeat_ngram_size=3,
    eos_token_id=tokenizer.eos_token_id,
    pad_token_id=tokenizer.eos_token_id,
)

# Containers for predictions and calibrated probabilities

y_pred  = []
y_proba = []

print("Running inference...\n")

for i in range(len(X_test_sel)):

    # Build the few-shot prompt for the current test patient

    prompt = build_prompt(
        X_train_sel, y_train,
        X_test_sel[i], selected_genes, N_SHOTS,
    )

    # Tokenise the prompt and move tensors to the target device

    inputs = tokenizer(
        prompt,
        return_tensors="pt",
        truncation=True,
        max_length=1024,
    ).to(DEVICE)

    # Run inference without gradient computation

    with torch.no_grad():
        output = model_llm.generate(
            **inputs,
            generation_config=gen_config_clf,
            output_scores=True,
            return_dict_in_generate=True,
        )

    # Decode the generated sequence and isolate the model response

    response       = tokenizer.decode(output.sequences[0], skip_special_tokens=True)
    response_clean = response[len(prompt):].strip().upper()

    # Extract token-level logits from the first generated position

    logits     = output.scores[0][0]
    proba_soft = torch.softmax(logits, dim=-1)

    # Retrieve token IDs for ALL and AML class labels

    all_tok = tokenizer.encode("ALL", add_special_tokens=False)[0]
    aml_tok = tokenizer.encode("AML", add_special_tokens=False)[0]

    # Compute normalised P(AML) from the two competing token probabilities

    p_all    = proba_soft[all_tok].item()
    p_aml    = proba_soft[aml_tok].item()
    prob_aml = p_aml / (p_all + p_aml + 1e-9)

    # Derive hard prediction from presence of class label in decoded response

    pred = 0 if "ALL" in response_clean else 1
    y_pred.append(pred)
    y_proba.append(prob_aml)

    print(
        f"  Patient {test_patient_ids[i]:>2} | "
        f"Resp: {response_clean[:8]:<8} | "
        f"Real: {'ALL' if y_test[i] == 0 else 'AML'} | "
        f"P(AML): {prob_aml:.3f}"
    )

